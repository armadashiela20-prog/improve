    private void jTable3MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable3MouseClicked
      int selectedRow = jTable3.getSelectedRow();

     if (selectedRow == -1) {
     return;
     }

     int originalIndex = displayedIndexes[selectedRow];

     Node current = itemList.getHead();

     for (int i = 0; i < originalIndex; i++) {
     current = current.getNext();
     }

     item selectedItem = current.getData();

     String photoPath = selectedItem.getPhotoPath();

     if (photoPath != null && !photoPath.isEmpty()) {

    javax.swing.ImageIcon originalImage =
            new javax.swing.ImageIcon(photoPath);

    java.awt.Image image = originalImage.getImage();

    java.awt.Image resizedImage = image.getScaledInstance(
            photoLabel.getWidth(),
            photoLabel.getHeight(),
            java.awt.Image.SCALE_SMOOTH);

    photoLabel.setText("");
    photoLabel.setIcon(new javax.swing.ImageIcon(resizedImage));

    } else {
    photoLabel.setIcon(null);
    photoLabel.setText("No Photo Available");
    }
    }//GEN-LAST:event_jTable3MouseClicked
