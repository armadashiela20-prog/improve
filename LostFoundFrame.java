    private void addRecord() {

    String name = jTextField1.getText().trim();
    String description = jTextField2.getText().trim();
    String location = jTextField3.getText().trim();
    String person = jTextField4.getText().trim();

    if (name.isEmpty() || description.isEmpty()
           ||  location.isEmpty() || person.isEmpty()) {

        JOptionPane.showMessageDialog(
                this, "Please fill in all fields!");
        return;
    }

    String type = (String) jComboBox1.getSelectedItem();
    String status = (String) jComboBox2.getSelectedItem();
    String date = LocalDate.now().toString();

    item newitem;

    if (type.equals("Lost Item")) {
        newitem = new LostItem(
                name, description, location,
                date, status, person);
    } else {
        newitem = new FoundItem(
                name, description, location,
                date, status, person);
    }

    newitem.setPhotoPath(selectedPhotoPath);
    
    JOptionPane.showMessageDialog(
        this,
        "Photo Path: " + newitem.getPhotoPath()
     );

    itemList.addItem(newitem);

    displayRecords();
    clearFields();

    selectedPhotoPath = null;
    photoLabel.setIcon(null);
    photoLabel.setText("No Photo Selected");

    JOptionPane.showMessageDialog(
            this, "Record added successfully!");
}
  

private void displayRecords() {

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) jTable3.getModel();

    model.setRowCount(0);
    displayedCount = 0;

    Node current = itemList.getHead();
    int originalIndex = 0;

    while (current != null && displayedCount < displayedIndexes.length) {

        item record = current.getData();

        model.addRow(new Object[]{
            record.getItemName(),
            record.getDescription(),
            record.getLocation(),
            record.getDateReported(),
            record.getItemType(),
            record.getPersonName(),
            record.getStatus()
        });

        displayedIndexes[displayedCount] = originalIndex;
        displayedCount++;

        current = current.getNext();
        originalIndex++;
    }
}

private void searchRecord() {

    String keyword = jTextField5.getText().trim();

    if (keyword.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter an Item Name!");
        return;
    }

    Node current = itemList.getHead();

    jTable3.setModel(new javax.swing.table.DefaultTableModel(
            new Object[][]{},
            new String[]{
                "Item Name",
                "Description",
                "Location",
                "Date Reported",
                "Item Type",
                "Person Name",
                "Status"
            }
    ));

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) jTable3.getModel();

    int count = 0;
    int index = 0;
    displayedCount = 0;

    while (current != null) {

        item record = current.getData();

        String searchable = (
                record.getItemName() + " "
                + record.getDescription() + " "
                + record.getLocation() + " "
                + record.getDateReported() + " "
                + record.getItemType() + " "
                + record.getPersonName() + " "
                + record.getStatus()
        ).toLowerCase();

        if (searchable.contains(keyword.toLowerCase())) {

            model.addRow(new Object[]{
                record.getItemName(),
                record.getDescription(),
                record.getLocation(),
                record.getDateReported(),
                record.getItemType(),
                record.getPersonName(),
                record.getStatus()
            });

            if (displayedCount < displayedIndexes.length) {
                displayedIndexes[displayedCount] = index;
                displayedCount++;
            }

            count++;
        }

        current = current.getNext();
        index++;
    }

    if (count == 0) {
        JOptionPane.showMessageDialog(this, "Item not found!");
    }
}
  private void updateRecord() {

    int selectedRow = jTable3.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(
                this, "Please select a record first!");
        return;
    }

    if (selectedRow >= displayedCount) {
        JOptionPane.showMessageDialog(
                this, "Invalid selected record!");
        return;
    }

    int originalIndex = displayedIndexes[selectedRow];

    String newStatus = (String) jComboBox2.getSelectedItem();

    boolean updated = itemList.updateStatus(originalIndex, newStatus);

    if (updated) {
        displayRecords();

        JOptionPane.showMessageDialog(
                this, "Status updated successfully!");
    } else {
        JOptionPane.showMessageDialog(
                this, "Unable to update record!");
    }
}
  private void deleteRecord() {

    int selectedRow = jTable3.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(
                this, "Please select a record first!");
        return;
    }

    if (selectedRow >= displayedCount) {
        JOptionPane.showMessageDialog(
                this, "Invalid selected record!");
        return;
    }

    int originalIndex = displayedIndexes[selectedRow];

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this record?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm == JOptionPane.YES_OPTION) {

        boolean deleted = itemList.deleteItem(originalIndex);

        if (deleted) {
            displayRecords();

            // Clear the photo preview
            photoLabel.setIcon(null);
            photoLabel.setText("No Photo Selected");

            JOptionPane.showMessageDialog(
                    this, "Record deleted successfully!");
        } else {
            JOptionPane.showMessageDialog(
                    this, "Unable to delete record!");
        }
      }
   }
  
